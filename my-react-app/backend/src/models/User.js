const mongoose=require("mongoose");
const userSchema=new mongoose.Schema(
{
    name:{
        type:String,
        required:true,
        trim:true
    },

    email:{
        type:String,
        required:true,
        unique:true,
        lowercase:true,
        match:[
        /^[^\s@]+@[^\s@]+\.[^\s@]+$/,
        "Invalid email format"
    ]
    },
    mobile:{
        type:String,
        required:true,
        match:[
            /^[0-9]{10}$/,
            "Mobile number must be 10 digits"
        ]
    },
    password:{
        type:String,
        required:true,
        select:false,
        minlength:6
    },
    role:{
        type:String,
        enum:["student","staff","admin"],
        default:"student"
    },
    department:{
        type:String,
        default:null
    },
    status:{
        type:String,
        enum:["active","inactive"],
        default:"active"
    },
    mustChangePassword:{
        type:Boolean,
        default:true
    },
},
{
    timestamps:true
}
);
module.exports=mongoose.model(
    "User",
    userSchema
);
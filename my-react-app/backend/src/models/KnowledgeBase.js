const mongoose=require("mongoose");
const knowledgeBaseSchema=new mongoose.Schema(
    {
        question:{
            type:String,
            required:true,
            trim:true
        },
        answer:{
            type:String,
            required:true
        },
        category:{
            type:String,
            required:true
        },
        keywords:{
            type:[String],
            default:[]
        },
        createdBy:{
            type:mongoose.Schema.Types.ObjectId,
            ref:"User"
        },
        isActive:{
            type:Boolean,
            default:true
        }
    },
    {
        timestamps:true
    }
);
module.exports=mongoose.model("KnowledgeBase",knowledgeBaseSchema);